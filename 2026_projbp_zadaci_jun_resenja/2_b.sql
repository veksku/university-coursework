CREATE TABLE KLIJENT (
    JMBG CHAR(13) PRIMARY KEY,
    IME VARCHAR(50) NOT NULL,
    PREZIME VARCHAR(50) NOT NULL
);

CREATE TABLE KARTICA (
    ID SERIAL PRIMARY KEY,
    DATUM_ISTEKA DATE NOT NULL,
    STANJE DECIMAL(10, 2) NOT NULL CHECK (STANJE >= 0),
    JMBG_KLIJENTA CHAR(13) NOT NULL,
    
    CONSTRAINT FK_KARTICA_KLIJENT
        FOREIGN KEY (JMBG_KLIJENTA)
        REFERENCES KLIJENT(JMBG)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE TABLE TRANSAKCIJA (
    RBR SERIAL,
    ID_KARTICE INT NOT NULL,
    IZNOS DECIMAL(10, 2) NOT NULL CHECK (IZNOS >= 0),
    VALUTA VARCHAR(3) NOT NULL,
    DATUM DATE NOT NULL,

    PRIMARY KEY (ID_KARTICE, RBR),

    CONSTRAINT FK_TRANSAKCIJA_KARTICA
        FOREIGN KEY (ID_KARTICE)
        REFERENCES KARTICA(ID)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE TABLE BANKOMAT (
    SIFRA SERIAL PRIMARY KEY,
    STANJE DECIMAL(10, 2) NOT NULL CHECK (STANJE >= 0),
    ZAMENA INT,
    UDALJENOST REAL NOT NULL CHECK(UDALJENOST > 0.0),
    CONSTRAINT FK_BANKOMAT_ZAMENA
        FOREIGN KEY (ZAMENA)
        REFERENCES BANKOMAT(SIFRA)
        ON DELETE SET NULL
        ON UPDATE CASCADE
);
